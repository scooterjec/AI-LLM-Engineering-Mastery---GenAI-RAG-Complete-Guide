# if statements and booleans

weather = "rainy"
if weather == 'rain':
    print("Don't forget your umbrella")
else:
    print("Grab your sunglasses")

age = 12
if age > 10:
    print("You're older than 10")
else:
    print("You're younger than 10")
    
is_tall = False
if is_tall:
    print("You're tall")
else:
    print("Not tall")